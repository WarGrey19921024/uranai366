SEKKI_BY_DEG = {s[0]: s for s in SEKKI}


def crossings(year_from: int, year_to: int, step_deg=5):
    """[year_from-01-01, year_to+1-01-01) JST で太陽黄経が step_deg の倍数を通る時刻"""
    jd = jd_from_jst(dt.datetime(year_from, 1, 1, tzinfo=JST))
    end = jd_from_jst(dt.datetime(year_to + 1, 1, 1, tzinfo=JST))
    prev = lon(jd)
    out = []
    while jd < end:
        nj = jd + 1
        cur = lon(nj)
        pk, ck = int(prev // step_deg), int(cur // step_deg)
        if pk != ck:
            target = (ck * step_deg) % 360
            a, b = jd, nj
            for _ in range(45):
                m = (a + b) / 2
                d = (lon(m) - target + 180) % 360 - 180
                if d < 0:
                    a = m
                else:
                    b = m
            out.append((target, (a + b) / 2))
        prev, jd = cur, nj
    return out


def kou_list(year: int):
    res = []
    for deg, jd in crossings(year, year):
        base = deg - (deg - 315) % 15  # その候が属する節気の度数
        base %= 360
        s = SEKKI_BY_DEG[base]
        idx = ((deg - base) % 360) // 5
        name, yomi = KOU[s[1]][idx]
        t = jst_from_jd(jd)
        res.append({
            "deg": deg, "jst": t.strftime("%Y-%m-%d %H:%M"), "date": t.strftime("%m%d"),
            "sekki": s[1] if idx == 0 else None, "sekki_yomi": s[2] if idx == 0 else None,
            "sekki_kind": s[3] if idx == 0 else None,
            "parent_sekki": s[1], "kou_no": idx + 1, "kou": name, "kou_yomi": yomi,
            "kou_serial": ((deg - 315) % 360) // 5 + 1,  # 立春初候=1 … 大寒末候=72
        })
    return res


def setsuiri(year_from=1900, year_to=2100):
    table = {}
    for deg, jd in crossings(year_from, year_to, step_deg=15):
        s = SEKKI_BY_DEG[deg]
        if s[3] != "節":
            continue
        t = jst_from_jd(jd)
        table.setdefault(str(t.year), {})[s[1]] = t.strftime("%Y-%m-%d %H:%M")
    return table


