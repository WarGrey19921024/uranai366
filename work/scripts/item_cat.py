import json, os, re

HERE = os.path.dirname(os.path.abspath(__file__))
_STONES = None


def _stones():
    global _STONES
    if _STONES is None:
        s = json.load(open(os.path.join(HERE, "..", "data", "src_stones.json"), encoding="utf-8"))["stones"]
        names = set()
        for x in s:
            names.add(x["name"])
            names.update(x.get("aka", []))
        names.update(["パワーストーン", "天然石", "原石", "真珠", "パール", "珊瑚", "サンゴ", "琥珀", "翡翠", "水晶", "瑪瑙"])
        _STONES = sorted((n for n in names if len(n) >= 2), key=len, reverse=True)
    return _STONES


