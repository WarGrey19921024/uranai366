def item_cat(name):
    n = str(name)
    for cat, pat in RULES:
        if cat == "stone":
            if any(s in n for s in _stones()):
                return "stone"
            continue
        if re.search(pat, n):
            return cat
    return "goods"


if __name__ == "__main__":
    import collections, glob
    c, other = collections.Counter(), []
    for p in glob.glob(os.path.join(HERE, "..", "text", "*.json")):
        d = json.load(open(p, encoding="utf-8"))
        for k, v in d.items():
            if not k.isdigit():
                continue
            names = [x["name"] for x in (v.get("y2027", {}).get("amulet", {}).get("items") or [])]
            names += [x["item"] for x in (v.get("fixed", {}).get("present") or [])]
            for nm in names:
                ct = item_cat(nm)
                c[ct] += 1
                if ct == "goods":
                    other.append(nm)
    print(c.most_common())
    print(len(other), sorted(set(other))[:200])
