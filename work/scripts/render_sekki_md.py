def d(s):
    return dt.datetime.strptime(s, "%Y-%m-%d %H:%M")


def boundary_analysis():
    """RANGE_FROM〜RANGE_TO年について、各候の開始日（MMDD）の幅と、
    MMDDごとに当たりうる候の集合を調べる"""
    starts = {}            # serial -> set(MMDD)
    by_mmdd = {}           # MMDD -> set(serial)
    allc = []
    for deg, jd in crossings(RANGE_FROM - 1, RANGE_TO + 1):
        t = jst_from_jd(jd)
        serial = ((deg - 315) % 360) // 5 + 1
        allc.append((t.date(), serial))
    for i, (day, serial) in enumerate(allc):
        if RANGE_FROM <= day.year <= RANGE_TO:
            starts.setdefault(serial, set()).add(day.strftime("%m%d"))
    for i in range(len(allc) - 1):
        a, s = allc[i]
        b, _ = allc[i + 1]
        x = a
        while x < b:
            if RANGE_FROM <= x.year <= RANGE_TO:
                by_mmdd.setdefault(x.strftime("%m%d"), set()).add(s)
            x += dt.timedelta(days=1)
    return starts, by_mmdd


